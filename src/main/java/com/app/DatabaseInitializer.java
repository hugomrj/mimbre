package com.app;

import io.micronaut.context.annotation.Value;
import io.micronaut.context.event.StartupEvent;
import io.micronaut.runtime.event.annotation.EventListener;
import jakarta.inject.Singleton;

import java.io.File;
import java.io.IOException;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.Statement;

@Singleton
public class DatabaseInitializer {

    private final DemoDataSeeder demoDataSeeder;
    private final BackupService backupService;
    private final boolean initEnabled;

    public DatabaseInitializer(DemoDataSeeder demoDataSeeder,
                               BackupService backupService,
                               @Value("${app.init.enabled:true}") boolean initEnabled) {
        this.demoDataSeeder = demoDataSeeder;
        this.backupService = backupService;
        this.initEnabled = initEnabled;
    }

    @EventListener
    public void onStartup(StartupEvent event) {
        if (!initEnabled) {
            return;
        }

        File dataDir = AppPaths.dataDir().toFile();
        if (!dataDir.exists()) {
            dataDir.mkdirs();
        }

        File initMarker = AppPaths.initMarker().toFile();
        boolean isFirstRun = !initMarker.exists();

        ensureEmptyDatabaseExists();

        if (isFirstRun) {
            demoDataSeeder.seed();

            try {
                initMarker.createNewFile();
            } catch (IOException e) {
                e.printStackTrace();
            }
        }

        backupService.respaldarDiario();
    }

    /**
     * Crea una base "plantilla" vacia, sin datos demo, para quien quiera empezar
     * de cero. El esquema principal lo versiona Flyway; esta copia se mantiene
     * por compatibilidad con el flujo anterior.
     */
    private void ensureEmptyDatabaseExists() {
        File emptyDbFile = AppPaths.emptyDatabaseFile().toFile();
        if (!emptyDbFile.exists()) {
            try (Connection conn = DriverManager.getConnection("jdbc:h2:file:" + AppPaths.dataDir().resolve("database_empty") + ";DB_CLOSE_DELAY=-1;AUTO_SERVER=TRUE", "sa", "")) {
                try (Statement stmt = conn.createStatement()) {
                    stmt.execute("CREATE TABLE IF NOT EXISTS CLIENTE (" +
                            "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                            "nombre VARCHAR(255), ruc_documento VARCHAR(255), telefono VARCHAR(255), email VARCHAR(255), direccion VARCHAR(255))");

                    stmt.execute("CREATE TABLE IF NOT EXISTS PRODUCTO (" +
                            "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                            "nombre VARCHAR(255), sku VARCHAR(255), precio DECIMAL(19, 2), stock INT, categoria VARCHAR(255))");

                    stmt.execute("CREATE TABLE IF NOT EXISTS PRODUCTO_CATEGORIA (" +
                            "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                            "nombre VARCHAR(255), descripcion VARCHAR(255))");

                    stmt.execute("CREATE TABLE IF NOT EXISTS PROVEEDOR (" +
                            "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                            "nombre VARCHAR(255), ruc VARCHAR(255), telefono VARCHAR(255), email VARCHAR(255), direccion VARCHAR(255))");

                    stmt.execute("CREATE TABLE IF NOT EXISTS VENTA (" +
                            "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                            "numero_factura VARCHAR(255), cliente_id BIGINT, cliente_nombre VARCHAR(255), fecha TIMESTAMP, condicion VARCHAR(255), monto_total DECIMAL(19, 2), estado VARCHAR(255), fecha_anulacion TIMESTAMP)");

                    stmt.execute("CREATE TABLE IF NOT EXISTS VENTA_DETALLE (" +
                            "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                            "venta_id BIGINT, producto_id BIGINT, producto_nombre VARCHAR(255), cantidad INT, precio_unitario DECIMAL(19, 2), subtotal DECIMAL(19, 2))");

                    stmt.execute("CREATE TABLE IF NOT EXISTS COMPRA (" +
                            "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                            "numero_factura VARCHAR(255), proveedor_id BIGINT, proveedor_nombre VARCHAR(255), fecha TIMESTAMP, condicion VARCHAR(255), monto_total DECIMAL(19, 2), estado VARCHAR(255), fecha_anulacion TIMESTAMP)");

                    stmt.execute("CREATE TABLE IF NOT EXISTS COMPRA_DETALLE (" +
                            "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, " +
                            "compra_id BIGINT, producto_id BIGINT, producto_nombre VARCHAR(255), cantidad INT, precio_costo DECIMAL(19, 2), subtotal DECIMAL(19, 2))");
                }
            } catch (Exception e) {
                e.printStackTrace();
            }
        }
    }
}
