-- V5: kardex de stock y datos de costo/stock minimo por producto.

ALTER TABLE producto ADD COLUMN IF NOT EXISTS costo_actual DECIMAL(19, 2) DEFAULT 0;
ALTER TABLE producto ADD COLUMN IF NOT EXISTS stock_minimo INT DEFAULT 5;

UPDATE producto SET costo_actual = 0 WHERE costo_actual IS NULL;
UPDATE producto SET stock_minimo = 5 WHERE stock_minimo IS NULL;

-- Costo de referencia: ultimo costo de compra registrado para el producto.
UPDATE producto p
SET costo_actual = COALESCE((
    SELECT cd.precio_costo
    FROM compra_detalle cd
    JOIN compra c ON c.id = cd.compra_id
    WHERE cd.producto_id = p.id
    ORDER BY c.fecha DESC, cd.id DESC
    LIMIT 1
), 0);

CREATE TABLE IF NOT EXISTS movimiento_stock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id BIGINT NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    cantidad INT NOT NULL,
    stock_anterior INT NOT NULL,
    stock_nuevo INT NOT NULL,
    costo_unitario DECIMAL(19, 2),
    origen_tipo VARCHAR(30),
    origen_id BIGINT,
    motivo VARCHAR(255),
    creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

ALTER TABLE movimiento_stock ADD CONSTRAINT IF NOT EXISTS fk_movimiento_producto
    FOREIGN KEY (producto_id) REFERENCES producto(id) ON DELETE RESTRICT;
ALTER TABLE movimiento_stock ADD CONSTRAINT IF NOT EXISTS chk_movimiento_cantidad
    CHECK (cantidad <> 0);
ALTER TABLE movimiento_stock ADD CONSTRAINT IF NOT EXISTS chk_movimiento_stock
    CHECK (stock_anterior >= 0 AND stock_nuevo >= 0);

CREATE INDEX IF NOT EXISTS ix_movimiento_producto ON movimiento_stock(producto_id);
CREATE INDEX IF NOT EXISTS ix_movimiento_fecha ON movimiento_stock(creado_en);
CREATE INDEX IF NOT EXISTS ix_movimiento_tipo ON movimiento_stock(tipo);

-- Saldo inicial: una fila por producto con existencia distinta de cero.
INSERT INTO movimiento_stock
    (producto_id, tipo, cantidad, stock_anterior, stock_nuevo, costo_unitario,
     origen_tipo, origen_id, motivo, creado_en)
SELECT id, 'INICIAL', stock, 0, stock, costo_actual,
       'MIGRACION', NULL, 'Stock inicial migrado', CURRENT_TIMESTAMP
FROM producto
WHERE stock IS NOT NULL AND stock <> 0;
