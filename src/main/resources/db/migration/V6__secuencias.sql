-- V6: secuencias de comprobantes para no depender de count() + 1.

CREATE TABLE IF NOT EXISTS secuencia_comprobante (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(20) NOT NULL,
    prefijo VARCHAR(20) NOT NULL,
    ultimo_numero BIGINT NOT NULL DEFAULT 0,
    longitud INT NOT NULL DEFAULT 7,
    creado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    actualizado_en TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_secuencia_tipo ON secuencia_comprobante(tipo);

-- Venta: arranca desde el mayor numero existente con el formato 001-001-0000000.
INSERT INTO secuencia_comprobante (tipo, prefijo, ultimo_numero, longitud, creado_en, actualizado_en)
SELECT 'VENTA', '001-001-',
       COALESCE((
           SELECT MAX(CAST(SUBSTRING(numero_factura, 9) AS BIGINT))
           FROM venta
           WHERE numero_factura LIKE '001-001-%'
       ), 0),
       7, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
WHERE NOT EXISTS (SELECT 1 FROM secuencia_comprobante WHERE tipo = 'VENTA');

-- Compra: arranca desde el mayor numero existente con el formato COMP-0000000.
INSERT INTO secuencia_comprobante (tipo, prefijo, ultimo_numero, longitud, creado_en, actualizado_en)
SELECT 'COMPRA', 'COMP-',
       COALESCE((
           SELECT MAX(CAST(SUBSTRING(numero_factura, 6) AS BIGINT))
           FROM compra
           WHERE numero_factura LIKE 'COMP-%'
       ), 0),
       7, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
WHERE NOT EXISTS (SELECT 1 FROM secuencia_comprobante WHERE tipo = 'COMPRA');
