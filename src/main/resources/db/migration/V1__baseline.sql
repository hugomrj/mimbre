-- V1: esquema inicial de Mimbre.
-- Refleja el modelo que antes creaba Micronaut Data con schema-generate=CREATE.
-- En una base existente, Flyway hace baseline en la version 1 y NO ejecuta este
-- script; en una base nueva, lo ejecuta y crea todo desde cero.

CREATE TABLE IF NOT EXISTS producto_categoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255),
    descripcion VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS producto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255),
    sku VARCHAR(255),
    precio DECIMAL(19, 2),
    stock INT,
    categoria VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS cliente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255),
    ruc_documento VARCHAR(255),
    telefono VARCHAR(255),
    email VARCHAR(255),
    direccion VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS proveedor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255),
    ruc VARCHAR(255),
    telefono VARCHAR(255),
    email VARCHAR(255),
    direccion VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS venta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_factura VARCHAR(255),
    cliente_id BIGINT,
    cliente_nombre VARCHAR(255),
    fecha TIMESTAMP,
    condicion VARCHAR(255),
    monto_total DECIMAL(19, 2),
    estado VARCHAR(255),
    fecha_anulacion TIMESTAMP
);

CREATE TABLE IF NOT EXISTS venta_detalle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id BIGINT,
    producto_id BIGINT,
    producto_nombre VARCHAR(255),
    cantidad INT,
    precio_unitario DECIMAL(19, 2),
    subtotal DECIMAL(19, 2)
);

CREATE TABLE IF NOT EXISTS compra (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_factura VARCHAR(255),
    proveedor_id BIGINT,
    proveedor_nombre VARCHAR(255),
    fecha TIMESTAMP,
    condicion VARCHAR(255),
    monto_total DECIMAL(19, 2),
    estado VARCHAR(255),
    fecha_anulacion TIMESTAMP
);

CREATE TABLE IF NOT EXISTS compra_detalle (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compra_id BIGINT,
    producto_id BIGINT,
    producto_nombre VARCHAR(255),
    cantidad INT,
    precio_costo DECIMAL(19, 2),
    subtotal DECIMAL(19, 2)
);
